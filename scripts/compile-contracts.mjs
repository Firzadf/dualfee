// Compiles contracts/*.sol with solc-js 0.8.28 and writes:
//   contracts/artifacts/<Name>.json    (abi + bytecode)
//   packages/sdk/src/artifacts.ts      (typed constants used by the SDK and the app)
import solc from 'solc';
import fs from 'node:fs';

const files = ['FeeRegistry.sol', 'SampleToken.sol'];
const sources = Object.fromEntries(files.map((f) => [f, { content: fs.readFileSync(`contracts/src/${f}`, 'utf8') }]));
const input = {
  language: 'Solidity',
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: 'cancun',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors ?? []).filter((e) => e.severity === 'error');
if (errors.length) { console.error(errors.map((e) => e.formattedMessage).join('\n')); process.exit(1); }

fs.mkdirSync('contracts/artifacts', { recursive: true });
let ts = `// AUTO-GENERATED by scripts/compile-contracts.mjs (solc ${solc.version()}). Do not edit.\n\n`;
for (const cs of Object.values(out.contracts)) {
  for (const [name, c] of Object.entries(cs)) {
    const art = { contractName: name, compiler: solc.version(), abi: c.abi, bytecode: '0x' + c.evm.bytecode.object };
    fs.writeFileSync(`contracts/artifacts/${name}.json`, JSON.stringify(art, null, 2) + '\n');
    ts += `export const ${name}Abi = ${JSON.stringify(c.abi)} as const;\n`;
    ts += `export const ${name}Bytecode = '0x${c.evm.bytecode.object}' as const;\n\n`;
    console.log(`${name}: ${c.evm.bytecode.object.length / 2} bytes`);
  }
}
fs.writeFileSync('packages/sdk/src/artifacts.ts', ts);
